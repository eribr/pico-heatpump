"""
Test to verify that calculation code generates the same bytes as combo recordings.

This test reads combo_metadata.json and compares expected bytes with generated bytes.
Uses nibe_protocol.py for byte generation.
"""

import json
import sys
from nibe_protocol import generate_nibe_packet

def load_combo_metadata():
    """Read combo_metadata.json"""
    with open("combo_metadata.json", "r", encoding="utf-8") as f:
        return json.load(f)

def hex_str_to_int(hex_str):
    """Convert '0xAC' to 172"""
    return int(hex_str, 16)

def generate_nibe_packet_wrapper(hour, minute, power, mode, temp, fan, ifeel):
    """Wrapper that calls nibe_protocol.generate_nibe_packet()"""
    return generate_nibe_packet(
        hour=hour,
        minute=minute,
        power=power,
        mode=mode,
        temp=temp,
        fan=fan,
        ifeel=ifeel
    )

def verify_recording(filename, expected_data, generated_data):
    """Compare expected data with generated data"""
    mismatches = []
    
    for i in range(min(len(expected_data), len(generated_data))):
        if expected_data[i] != generated_data[i]:
            mismatches.append({
                "byte_index": i,
                "expected": f"0x{expected_data[i]:02X}",
                "generated": f"0x{generated_data[i]:02X}"
            })
    
    if len(expected_data) != len(generated_data):
        mismatches.append({
            "error": "length_mismatch",
            "expected_length": len(expected_data),
            "generated_length": len(generated_data)
        })
    
    return {
        "filename": filename,
        "passed": len(mismatches) == 0,
        "mismatches": mismatches
    }

def run_tests():
    """Run all tests"""
    metadata = load_combo_metadata()
    recordings = metadata["recordings"]
    
    print("=" * 70)
    print("COMBO VERIFICATION TEST")
    print("=" * 70)
    print()
    print(f"Total recordings: {len(recordings)}")
    print()
    
    results = []
    passed_count = 0
    failed_count = 0
    
    for filename, data in sorted(recordings.items()):
        # Extract data from metadata JSON
        time_info = data["time"]
        settings = data["settings"]
        expected_bytes_dict = data["bytes"]
        expected_bytes = [hex_str_to_int(expected_bytes_dict[f"B{i}"]) for i in range(11)]
        
        # Feed time and settings from JSON to generator
        generated_bytes = generate_nibe_packet_wrapper(
            hour=time_info["hour"],
            minute=time_info["minute"],
            power=settings["power"],
            mode=settings["mode"],
            temp=settings["temp"],
            fan=settings["fan"],
            ifeel=settings["ifeel"]
        )
        
        # Verify
        result = verify_recording(filename, expected_bytes, generated_bytes)
        results.append(result)
        
        if result["passed"]:
            passed_count += 1
            status = "[PASS]"
        else:
            failed_count += 1
            status = "[FAIL]"
        
        print(f"{status} | {filename:20} | {time_info['hour']:02d}:{time_info['minute']:02d}")
        
        if not result["passed"] and result["mismatches"]:
            # Show first 3 mismatches
            for mismatch in result["mismatches"][:3]:
                if "byte_index" in mismatch:
                    print(f"       -> B{mismatch['byte_index']}: expected {mismatch['expected']}, got {mismatch['generated']}")
                else:
                    print(f"       -> {mismatch}")
    
    print()
    print("=" * 70)
    print(f"RESULT: {passed_count} pass, {failed_count} fail of {len(recordings)} tests")
    print("=" * 70)
    print()
    
    if failed_count == 0:
        print("*** ALL TESTS PASSED!")
        print("Byte generation matches combo recordings perfectly.")
        return 0
    else:
        print("!!! IMPLEMENT generate_nibe_packet_wrapper() to fix tests.")
        print()
        print("Next steps:")
        print("1. Analyze byte patterns in combo_metadata.json")
        print("2. Implement correct encoding for B2-B10 based on settings and time")
        print("3. Run this test again until all pass")
        return 1

if __name__ == "__main__":
    sys.exit(run_tests())
